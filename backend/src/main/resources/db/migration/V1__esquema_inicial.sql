-- Esquema inicial del MVP: usuarios, credenciales, tiers, contenido y progreso.

-- Búsqueda sin distinguir acentos ("cardiologia" encuentra "Cardiología").
CREATE EXTENSION IF NOT EXISTS unaccent;

CREATE TABLE tier (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(30)  NOT NULL,
    nombre        VARCHAR(80)  NOT NULL,
    descripcion   TEXT,
    orden_acceso  INTEGER      NOT NULL,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_tier_codigo UNIQUE (codigo),
    CONSTRAINT uk_tier_orden_acceso UNIQUE (orden_acceso)
);

CREATE TABLE usuarios (
    id          UUID         PRIMARY KEY,
    nombre      VARCHAR(80)  NOT NULL,
    apellido    VARCHAR(100) NOT NULL,
    correo      VARCHAR(254) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    -- El backend normaliza el correo; la restricción impide duplicados por mayúsculas.
    CONSTRAINT ck_usuarios_correo_normalizado CHECK (correo = lower(btrim(correo)))
);

CREATE TABLE usuarios_sistema (
    usuario_id     UUID         PRIMARY KEY REFERENCES usuarios (id) ON DELETE CASCADE,
    password_hash  VARCHAR(255) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    tier_id        BIGINT       NOT NULL REFERENCES tier (id),
    estado         VARCHAR(20)  NOT NULL,
    last_login_at  TIMESTAMPTZ,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_usuarios_sistema_rol CHECK (rol IN ('ALUMNO', 'ADMIN')),
    CONSTRAINT ck_usuarios_sistema_estado CHECK (estado IN ('ACTIVO', 'BLOQUEADO'))
);

CREATE INDEX ix_usuarios_sistema_tier ON usuarios_sistema (tier_id);

CREATE TABLE contenido (
    id                        UUID         PRIMARY KEY,
    titulo                    VARCHAR(200) NOT NULL,
    slug                      VARCHAR(220) NOT NULL,
    area_medica               VARCHAR(100) NOT NULL,
    objetivo_aprendizaje      TEXT,
    resumen                   TEXT         NOT NULL,
    -- Un punto clave por línea.
    puntos_clave              TEXT         NOT NULL,
    aplicacion_clinica        TEXT,
    metodo_aprendizaje        VARCHAR(30)  NOT NULL DEFAULT 'LECTURA_GUIADA',
    tier_minimo_id            BIGINT       NOT NULL REFERENCES tier (id),
    fuente_titulo             VARCHAR(300) NOT NULL,
    fuente_autores            TEXT,
    fuente_url                TEXT,
    fuente_doi                VARCHAR(150),
    fecha_publicacion_fuente  DATE,
    fecha_revision            DATE         NOT NULL,
    tiempo_lectura_minutos    INTEGER      NOT NULL,
    estado                    VARCHAR(20)  NOT NULL,
    created_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_contenido_slug UNIQUE (slug),
    CONSTRAINT ck_contenido_slug_formato CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_contenido_metodo CHECK (metodo_aprendizaje IN ('LECTURA_GUIADA')),
    CONSTRAINT ck_contenido_estado CHECK (estado IN ('BORRADOR', 'PUBLICADO')),
    CONSTRAINT ck_contenido_tiempo_lectura CHECK (tiempo_lectura_minutos > 0)
);

CREATE INDEX ix_contenido_estado ON contenido (estado);
CREATE INDEX ix_contenido_area_medica ON contenido (area_medica);
CREATE INDEX ix_contenido_tier_minimo ON contenido (tier_minimo_id);

CREATE TABLE usuario_contenido_progreso (
    usuario_id          UUID        NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    contenido_id        UUID        NOT NULL REFERENCES contenido (id) ON DELETE CASCADE,
    estado              VARCHAR(20) NOT NULL,
    ultima_consulta_at  TIMESTAMPTZ NOT NULL,
    completado_at       TIMESTAMPTZ,
    PRIMARY KEY (usuario_id, contenido_id),
    CONSTRAINT ck_progreso_estado CHECK (estado IN ('EN_PROGRESO', 'COMPLETADO')),
    CONSTRAINT ck_progreso_completado CHECK ((estado = 'COMPLETADO') = (completado_at IS NOT NULL))
);

CREATE INDEX ix_progreso_usuario_ultima_consulta
    ON usuario_contenido_progreso (usuario_id, ultima_consulta_at DESC);
